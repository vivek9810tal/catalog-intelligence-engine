async def run_agentic_pipeline(repo_url: str, branch: str):
    # Setup the subprocess parameters to launch your mcp_server.py
    server_params = StdioServerParameters(
    command=sys.executable,
    args=["-u", "mcp_server2.py"], 
    env=None
    )

    # Initialize the MCP connection over stdio
    async with stdio_client(server_params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            
            # Wrap node functions to inject the active MCP session
            workflow = StateGraph(CICDState)
            workflow.add_node("checkout", lambda state: asyncio.run_coroutine_threadsafe(stage_checkout(state, session), asyncio.get_running_loop()).result())
            workflow.add_node("scan", lambda state: asyncio.run_coroutine_threadsafe(stage_scan_and_patch(state, session), asyncio.get_running_loop()).result())
            workflow.add_node("unit_test", lambda state: asyncio.run_coroutine_threadsafe(stage_unit_test(state, session), asyncio.get_running_loop()).result())
            workflow.add_node("package", lambda state: asyncio.run_coroutine_threadsafe(stage_package_containerize(state, session), asyncio.get_running_loop()).result())
            workflow.add_node("automation", lambda state: asyncio.run_coroutine_threadsafe(stage_automation_test(state, session), asyncio.get_running_loop()).result())
            workflow.add_node("deploy", lambda state: asyncio.run_coroutine_threadsafe(stage_deploy_uat(state, session), asyncio.get_running_loop()).result())

            workflow.set_entry_point("checkout")
            workflow.add_edge("checkout", "scan")
            workflow.add_edge("scan", "unit_test") # Self-healing handles the loop internally now
            workflow.add_edge("unit_test", "package")
            workflow.add_edge("package", "automation")
            workflow.add_edge("automation", "deploy")
            workflow.add_edge("deploy", END)

            pipeline = workflow.compile()
            
            initial_state = {
                "repo_url": repo_url,
                "branch": branch,
                "scan_passed": False,
                "image_tag": "",
                "pipeline_log": []
            }
            
            print("\n" + "="*50)
            print("INITIALIZING AGENTIC CI/CD PIPELINE")
            print("="*50 + "\n")
            
            final_state = pipeline.invoke(initial_state)
            
            print("\n" + "="*50)
            print("🎉 PIPELINE COMPLETED SUCCESSFULLY")
            print(f"📦 Final Image Tag: {final_state['image_tag']}")
            print("="*50 + "\n")
            
            return final_state

