# In a full LangChain/MCP integration, tools are dynamically loaded via the session.
# For this PoV, we simulate the tool execution node dynamically calling the MCP client.

async def stage_checkout(state: CICDState, mcp_session: ClientSession):
    print("🚀 [STAGE 1] Agent Analyst: Requesting Git Checkout...")
    # The LLM reasons, decides to use the tool, and the MCP session executes it
    result = await mcp_session.call_tool("checkout_github_repo", {"repo_url": state["repo_url"], "branch": state["branch"]})
    return {"pipeline_log": [f"CHECKOUT: {result.content[0].text}"]}

async def stage_scan_and_patch(state: CICDState, mcp_session: ClientSession):
    print("🛡️ [STAGE 2] Security Agent: Initiating Code & Dependency Scan...")
    scan_result = await mcp_session.call_tool("run_security_scan", {"target_dir": "./workspace"})
    scan_text = scan_result.content[0].text
    
    if "FAILED" in scan_text:
        print(f"   ❌ Vulnerability Detected: {scan_text}")
        print("   🔧 [SELF-HEALING] Security Agent automatically generating and applying patch...")
        
        # Agent dynamically uses the patch tool
        patch_result = await mcp_session.call_tool("apply_code_patch", {
            "file_path": "requirements.txt", 
            "patch_content": "requests>=2.31.0"
        })
        print(f"   ✅ Patch Applied: {patch_result.content[0].text}")
        return {"scan_passed": True, "pipeline_log": ["SCAN FAILED -> AUTOPATCHED -> SCAN PASSED"]}
        
    return {"scan_passed": True, "pipeline_log": ["SCAN PASSED: Clean codebase."]}

async def stage_unit_test(state: CICDState, mcp_session: ClientSession):
    print("🧪 [STAGE 3] QA Agent: Executing Unit Tests...")
    result = await mcp_session.call_tool("execute_unit_tests", {"test_suite": "pytest tests/"})
    return {"pipeline_log": [f"UNIT TESTS: {result.content[0].text}"]}

async def stage_package_containerize(state: CICDState, mcp_session: ClientSession):
    print("📦 [STAGE 4] Build Agent: Packaging & Containerizing...")
    result = await mcp_session.call_tool("package_and_containerize", {"app_name": "agentic-pov"})
    output = result.content[0].text
    image_tag = output.split("Tag: ")[1] if "Tag: " in output else "latest"
    return {"image_tag": image_tag, "pipeline_log": [f"BUILD: {output}"]}

async def stage_automation_test(state: CICDState, mcp_session: ClientSession):
    print("🤖 [STAGE 5] QA Agent: Executing UI/API Automation...")
    result = await mcp_session.call_tool("execute_automation_tests", {"image_tag": state.get("image_tag", "latest")})
    return {"pipeline_log": [f"AUTOMATION: {result.content[0].text}"]}

async def stage_deploy_uat(state: CICDState, mcp_session: ClientSession):
    print("☁️ [STAGE 6] Release Manager: Deploying to UAT...")
    result = await mcp_session.call_tool("deploy_to_uat", {"image_tag": state.get("image_tag", "latest")})
    return {"pipeline_log": [f"DEPLOY: {result.content[0].text}"]}

